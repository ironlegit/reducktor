#!/usr/bin/env bash
# zero-network guarantee for the CSP claim.
# Reinstalls exactly what the lockfile pins, regenerates vendor/,
# and fails if the shipped builds contain any exfiltration sink.
set -euo pipefail

VENDOR_DIR="vendor"
SINKS=('fetch(' 'XMLHttpRequest' 'sendBeacon' 'WebSocket' 'import(')

echo "==> npm ci (install exactly what package-lock.json pins)"
npm ci

echo "==> Regenerating ${VENDOR_DIR}/ from node_modules"
mkdir -p "${VENDOR_DIR}"
cp node_modules/compromise/builds/compromise.js "${VENDOR_DIR}/compromise.js"
cp node_modules/compromise-dates/builds/compromise-dates.min.js \
  "${VENDOR_DIR}/compromise-dates.min.js"

echo "==> Auditing shipped builds for exfiltration sinks"
fail=0
for sink in "${SINKS[@]}"; do
  if grep -RInF -- "${sink}" "${VENDOR_DIR}" >/tmp/vendor-sink-hits.txt 2>&1; then
    echo "FAIL: exfil sink '${sink}' found in ${VENDOR_DIR}:"
    cat /tmp/vendor-sink-hits.txt
    fail=1
  else
    echo "ok: no '${sink}' in ${VENDOR_DIR}/"
  fi
done

if [ "${fail}" -ne 0 ]; then
  echo "==> AUDIT FAILED: vendor builds contain network sinks."
  exit 1
fi

echo "==> AUDIT PASSED: vendor builds are network-free."

# --- Regenerate MANIFEST.md ---
V_DATE=$(date -u +%Y-%m-%d)
C_VER=$(node -p "require('./node_modules/compromise/package.json').version")
D_VER=$(node -p "require('./node_modules/compromise-dates/package.json').version")
C_SHA=$(sha256sum "${VENDOR_DIR}/compromise.js" | cut -d' ' -f1)
D_SHA=$(sha256sum "${VENDOR_DIR}/compromise-dates.min.js" | cut -d' ' -f1)

cat >"${VENDOR_DIR}/MANIFEST.md" <<EOF
# Vendored builds — generated by scripts/vendor-audit.sh. Do not edit.

Generated ${V_DATE} from package-lock.json via \`npm ci\` (integrity-verified).

## compromise v${C_VER}
- file: vendor/compromise.js ← node_modules/compromise/builds/compromise.js
- sha256: ${C_SHA}

## compromise-dates v${D_VER}
- file: vendor/compromise-dates.min.js ← node_modules/compromise-dates/builds/compromise-dates.min.js
- sha256: ${D_SHA}

Version history: git log of this file.
EOF
